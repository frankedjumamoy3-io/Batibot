export function getTopicImage(worldId: string, topicTitle?: string) {
  if (!topicTitle) {
    return undefined;
  }

  const topicKey = topicTitle
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

  const instructionalFallbackWorldId = UPPER_GRADE_TOPIC_IMAGE_FALLBACKS[topicKey];

  return (
    TOPIC_IMAGES[`${worldId}-${topicKey}`] ??
    (instructionalFallbackWorldId ? WORLD_IMAGES[instructionalFallbackWorldId] : undefined) ??
    WORLD_IMAGES[worldId]
  );
}

