// Export bundled asset identifiers only; never include credentials or binary media.
const fs = require('node:fs');
const path = require('node:path');
const Module = require('node:module');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const resolve = Module._resolveFilename;
Module._resolveFilename = function(request, parent, ...args) { return resolve.call(this, request.startsWith('@/') ? path.join(root, request.slice(2)) : request, parent, ...args); };
require.extensions['.ts'] = (module, file) => module._compile(ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText, file);
for (const extension of ['.png', '.jpg', '.jpeg', '.webp', '.mp3', '.wav']) require.extensions[extension] = module => { module.exports = 1; };
const { batibotAssetRegistry } = require('../src/assets/assetRegistry');
const keys = Object.entries(batibotAssetRegistry).filter(([, asset]) => asset.source).map(([key]) => key).sort();
const output = '// Generated by Batibot-frontend/scripts/export-api-assets.cjs.\nexport const bundledAssetIds = new Set<string>(' + JSON.stringify(keys, null, 2) + ');\n';
if (process.argv[2]) fs.writeFileSync(path.resolve(process.argv[2]), output);
else process.stdout.write(output);
